/**
 * Shared image pipeline for case-study assets: PNG buffer → WebP on disk,
 * plus a manifest.json that records dimensions, source, and alt text.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

export const MAX_WIDTH = 2000;
export const WEBP_QUALITY = 82;
const MIN_QUALITY = 60;
const KB = 1024;

/** Mirrors the budgets in scripts/validate-performance.mjs. */
export function budgetFor(fileName) {
	return /hero|poster/.test(fileName) ? 220 * KB : 350 * KB;
}

export function mediaDirFor(project) {
	const dir = join(process.cwd(), "public", "media", `${project}-case-study`);
	mkdirSync(dir, { recursive: true });
	return dir;
}

/**
 * Converts to WebP at WEBP_QUALITY, capped at MAX_WIDTH. If the result is over
 * the repo's budget, steps quality down until it fits (or hits MIN_QUALITY).
 */
export async function writeWebp(input, outPath, fileName) {
	const budget = budgetFor(fileName);
	let quality = WEBP_QUALITY;
	let output;

	for (;;) {
		output = await sharp(input)
			.resize({ width: MAX_WIDTH, withoutEnlargement: true })
			.webp({ quality, effort: 6 })
			.toBuffer({ resolveWithObject: true });
		if (output.data.length <= budget || quality <= MIN_QUALITY) break;
		quality -= 4;
	}

	writeFileSync(outPath, output.data);
	return {
		width: output.info.width,
		height: output.info.height,
		bytes: output.data.length,
		quality,
		overBudget: output.data.length > budget,
	};
}

export function updateManifest(dir, entries) {
	const path = join(dir, "manifest.json");
	const manifest = existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : { images: [] };
	const byFile = new Map(manifest.images.map((image) => [image.file, image]));

	for (const entry of entries) {
		byFile.set(entry.file, entry);
	}

	manifest.images = [...byFile.values()].sort((a, b) => a.file.localeCompare(b.file));
	writeFileSync(path, `${JSON.stringify(manifest, null, "\t")}\n`);
	writeGeneratedMediaModule();
	return path;
}

/**
 * Rebuilds src/data/caseStudyMedia.generated.ts from every case-study manifest,
 * so the site reads alt text and dimensions from one source.
 */
export function writeGeneratedMediaModule() {
	const mediaRoot = join(process.cwd(), "public", "media");
	const entries = {};

	for (const dir of readdirSync(mediaRoot).filter((name) => name.endsWith("-case-study")).sort()) {
		const path = join(mediaRoot, dir, "manifest.json");
		if (!existsSync(path)) continue;
		for (const image of JSON.parse(readFileSync(path, "utf8")).images) {
			entries[`/media/${dir}/${image.file}`] = { width: image.width, height: image.height, alt: image.alt };
		}
	}

	const out = join(process.cwd(), "src", "data", "caseStudyMedia.generated.ts");
	writeFileSync(
		out,
		[
			"// Generated by scripts/lib/image-pipeline.mjs from public/media/*-case-study/manifest.json.",
			"// Do not edit by hand: re-run the asset scripts instead.",
			"",
			"export type CaseStudyMediaEntry = { width: number; height: number; alt: string };",
			"",
			`export const CASE_STUDY_MEDIA: Record<string, CaseStudyMediaEntry> = ${JSON.stringify(entries, null, "\t")};`,
			"",
		].join("\n"),
	);
}

export function printReport(rows) {
	console.log("\nfile                              KB   width × height  quality");
	for (const row of rows) {
		const flag = row.overBudget ? "  ⚠ over budget" : row.quality < WEBP_QUALITY ? "  (recompressed)" : "";
		console.log(
			`${row.file.padEnd(32)} ${String(Math.round(row.bytes / KB)).padStart(4)}   ${`${row.width} × ${row.height}`.padEnd(14)}  ${row.quality}${flag}`,
		);
	}
}
